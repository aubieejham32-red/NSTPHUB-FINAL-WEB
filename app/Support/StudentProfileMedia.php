<?php

namespace App\Support;

use Endroid\QrCode\Encoding\Encoding;
use Endroid\QrCode\ErrorCorrectionLevel;
use Endroid\QrCode\QrCode;
use Endroid\QrCode\RoundBlockSizeMode;
use Endroid\QrCode\Writer\SvgWriter;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Storage;
use Throwable;

/**
 * Image sources for authenticated student profile pages.
 *
 * Data URIs avoid a second cookie-authenticated request for each <img> and
 * work when Railway's web server does not serve public/storage symlinks.
 * Never put these sources on a public page or in a shared cache.
 */
final class StudentProfileMedia
{
    public static function qrCode(?string $token): ?string
    {
        $token = trim((string) $token);

        if ($token === '') {
            return null;
        }

        try {
            $qrCode = new QrCode(
                data: 'NSTPHUB:ATTENDANCE:'.$token,
                encoding: new Encoding('UTF-8'),
                errorCorrectionLevel: ErrorCorrectionLevel::High,
                size: 420,
                margin: 12,
                roundBlockSizeMode: RoundBlockSizeMode::Margin,
            );

            // SVG avoids the GD dependency for this authenticated page.
            return (new SvgWriter())->write($qrCode)->getDataUri();
        } catch (Throwable $exception) {
            Log::error('Unable to render student profile QR image.', [
                'error' => $exception->getMessage(),
            ]);

            return null;
        }
    }

    public static function signature(?string $path): ?string
    {
        $path = trim((string) $path);

        if ($path === '' || str_contains($path, '..') || str_starts_with($path, '/')) {
            return null;
        }

        $extension = strtolower(pathinfo($path, PATHINFO_EXTENSION));
        $mime = match ($extension) {
            'svg' => 'image/svg+xml',
            'png' => 'image/png',
            'jpg', 'jpeg' => 'image/jpeg',
            'webp' => 'image/webp',
            default => null,
        };

        if ($mime === null) {
            return null;
        }

        try {
            // Current signatures are private; historical installs used public.
            $disk = Storage::disk('local');

            if (!$disk->exists($path)) {
                $disk = Storage::disk('public');
            }

            if (!$disk->exists($path)) {
                Log::warning('Student profile signature file not found.');

                return null;
            }

            $bytes = $disk->get($path);

            if (!is_string($bytes) || $bytes === '' || strlen($bytes) > 2_000_000) {
                return null;
            }

            if ($extension === 'svg') {
                // SVG is generated by the app, but reject unsafe or invalid XML.
                if (
                    stripos($bytes, '<svg') === false
                    || preg_match('/<!DOCTYPE|<!ENTITY|<script\b|<foreignObject\b|\bon[a-z]+\s*=|\b(?:href|xlink:href)\s*=/i', $bytes)
                ) {
                    return null;
                }

                $document = new \DOMDocument();

                if (!@$document->loadXML($bytes, LIBXML_NONET | LIBXML_NOERROR | LIBXML_NOWARNING)) {
                    Log::warning('Student profile signature is invalid SVG XML.');

                    return null;
                }
            }

            return 'data:'.$mime.';base64,'.base64_encode($bytes);
        } catch (Throwable $exception) {
            Log::error('Unable to render student profile signature.', [
                'error' => $exception->getMessage(),
            ]);

            return null;
        }
    }
}
